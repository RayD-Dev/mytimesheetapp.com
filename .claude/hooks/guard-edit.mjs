// Protects files that are generated or owned elsewhere.
import { permission, readEvent, repoPath } from './lib.mjs'

const rules = [
  {
    prefix: 'web/src/shared/api/generated/',
    decision: 'deny',
    reason: 'Generated by orval from contract/openapi.yaml. Change the contract and run pnpm codegen instead.',
  },
  {
    prefix: 'docs/notion/',
    decision: 'ask',
    reason: 'Read-only copy of Notion. Edit the Notion page, then run docs-sync.',
  },
  {
    prefix: 'mockup/approved/',
    decision: 'ask',
    reason: 'Approved screenshots change only when the user approves a mock-up round.',
  },
]

const event = readEvent()
const path = repoPath(event, event.tool_input?.file_path)
const rule = path && rules.find((r) => path.startsWith(r.prefix))
if (rule) permission(rule.decision, `${path}: ${rule.reason}`)
